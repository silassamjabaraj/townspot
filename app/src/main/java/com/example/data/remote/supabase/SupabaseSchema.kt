package com.example.data.remote.supabase

object SupabaseSchema {
    const val SQL_SETUP_SCRIPT = """
-- =========================================================================
-- TownSpot Supabase PostgreSQL Database Setup
-- Run this in your Supabase Project -> SQL Editor -> Run
-- =========================================================================

-- 1. Businesses Table
CREATE TABLE IF NOT EXISTS public.businesses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    category TEXT NOT NULL,
    tagline TEXT DEFAULT '',
    description TEXT DEFAULT '',
    address TEXT DEFAULT '',
    neighborhood TEXT DEFAULT '',
    phone TEXT DEFAULT '',
    website TEXT DEFAULT '',
    email TEXT DEFAULT '',
    hours TEXT DEFAULT '',
    is_open_now BOOLEAN DEFAULT true,
    price_level TEXT DEFAULT '$$',
    rating REAL DEFAULT 5.0,
    review_count INTEGER DEFAULT 1,
    is_verified BOOLEAN DEFAULT false,
    is_featured BOOLEAN DEFAULT false,
    is_saved BOOLEAN DEFAULT false,
    latitude DOUBLE PRECISION DEFAULT 37.7749,
    longitude DOUBLE PRECISION DEFAULT -122.4194,
    special_offer TEXT,
    tags TEXT DEFAULT '',
    category_icon_name TEXT DEFAULT 'store',
    accent_color_hex TEXT DEFAULT '#0F766E',
    image_res_name TEXT,
    image_uri TEXT,
    claimed_by_owner_email TEXT,
    claimed_by_owner_name TEXT,
    is_claimed BOOLEAN DEFAULT false,
    created_at BIGINT DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

-- 2. Reviews Table
CREATE TABLE IF NOT EXISTS public.reviews (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT REFERENCES public.businesses(id) ON DELETE CASCADE,
    author_name TEXT NOT NULL,
    rating INTEGER NOT NULL,
    comment TEXT NOT NULL,
    date_string TEXT NOT NULL,
    helpful_count INTEGER DEFAULT 0
);

-- 3. Promotions Table
CREATE TABLE IF NOT EXISTS public.promotions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    business_id BIGINT REFERENCES public.businesses(id) ON DELETE CASCADE,
    business_name TEXT NOT NULL,
    category TEXT NOT NULL,
    title TEXT NOT NULL,
    discount_description TEXT NOT NULL,
    promo_code TEXT,
    terms TEXT DEFAULT 'Present this code in-store or mention during your visit.',
    valid_until TEXT DEFAULT 'Limited Time Community Offer',
    image_res_name TEXT,
    posted_by_owner_email TEXT NOT NULL,
    created_at BIGINT DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

-- 4. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email TEXT UNIQUE NOT NULL,
    full_name TEXT NOT NULL,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'Resident',
    business_name TEXT,
    avatar_url TEXT,
    created_at BIGINT DEFAULT (EXTRACT(EPOCH FROM NOW()) * 1000)::BIGINT
);

-- 5. Row Level Security & Public API Policies
ALTER TABLE public.businesses ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.reviews ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.promotions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;

-- Allow anonymous API key read and write for TownSpot mobile app
CREATE POLICY "Allow public read businesses" ON public.businesses FOR SELECT USING (true);
CREATE POLICY "Allow public all businesses" ON public.businesses FOR ALL USING (true);

CREATE POLICY "Allow public read reviews" ON public.reviews FOR SELECT USING (true);
CREATE POLICY "Allow public all reviews" ON public.reviews FOR ALL USING (true);

CREATE POLICY "Allow public read promotions" ON public.promotions FOR SELECT USING (true);
CREATE POLICY "Allow public all promotions" ON public.promotions FOR ALL USING (true);

CREATE POLICY "Allow public read users" ON public.users FOR SELECT USING (true);
CREATE POLICY "Allow public all users" ON public.users FOR ALL USING (true);
"""
}
